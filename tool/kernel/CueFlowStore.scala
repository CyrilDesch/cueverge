// @what: a Kyo FlowStore whose record is append-only CUE. Kyo's memory store coordinates, this one journals each write.
// @why: the journal is a meet of facts, so a line may land in any order and any number of times.
// @ref: @/tool/kernel/README.md

package kernel

import kyo.*

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Path as JPath, StandardOpenOption}
import scala.collection.mutable

final class CueFlowStore private (inner: FlowStore, dir: JPath, mutex: Meter) extends FlowStore:

    // @what: What the journal already holds, per execution.
    private val fieldsSeen = mutable.Map.empty[String, mutable.Set[String]]
    private val eventsSeen = mutable.Map.empty[String, Int]

    private def file(eid: Flow.Id.Execution): JPath = dir.resolve(s"${eid.value}.gen.cue")

    private def key(eid: Flow.Id.Execution): String = ujson.Str(eid.value).render()

    private def append(eid: Flow.Id.Execution, lines: Seq[String])(using Frame): Unit < Sync =
        if lines.isEmpty then Kyo.unit
        else
            Sync.defer {
                val f = file(eid)
                if !Files.exists(f) then
                    Files.createDirectories(dir): Unit
                    Files.writeString(f, "// Generated by the kernel: the journal of one Flow execution. Append-only.\npackage journal\n\n"): Unit
                Files.writeString(f, lines.mkString("", "\n", "\n"), UTF_8, StandardOpenOption.APPEND): Unit
            }

    // @what: A field as CUE. Its tag, and its value as data when it is JSON (it always is in kyo-flow).
    private def fieldLine(eid: Flow.Id.Execution, name: String, fd: FlowStore.FieldData)(using Frame): String =
        val tag   = ujson.read(Json.encode(fd)).obj("tag")
        val value = scala.util.Try(ujson.read(fd.value)).getOrElse(ujson.Str(fd.value))
        s"executions: ${key(eid)}: fields: ${ujson.Str(name).render()}: ${ujson.Obj("tag" -> tag, "value" -> value).render()}"

    // @what: Brings the journal up to what the memory store holds for eid.
    private def sync(eid: Flow.Id.Execution)(using Frame): Unit < (Async & Abort[FlowStoreException]) =
        Abort.recover[Closed](_ => Kyo.unit) {
            mutex.run {
                for
                    fields <- inner.getAllFields(eid)
                    seen   <- Sync.defer(eventsSeen.getOrElse(eid.value, 0))
                    page   <- inner.getHistory(eid, Absent, seen)
                    _ <- Sync.defer {
                        val known = fieldsSeen.getOrElseUpdate(eid.value, mutable.Set.empty)
                        val newFields = fields.foldLeft(Seq.empty[String]) { (acc, name, fd) =>
                            if known.contains(name) then acc else { known += name; acc :+ fieldLine(eid, name, fd) }
                        }
                        val newEvents = page.events.toSeq.zipWithIndex.map { (ev, i) =>
                            val json = Json.encode(ev)
                            say(eid, json)
                            s"executions: ${key(eid)}: events: \"${"%06d".format(seen + i)}\": $json"
                        }
                        eventsSeen(eid.value) = seen + page.events.size
                        newFields ++ newEvents
                    }.map(lines => append(eid, lines))
                yield ()
            }
        }

    // --- Console: one line per node, as the journal receives it ---

    // @why: the engine writes StepStarted when it records a node, not when it starts it.
    // @what: so the time of a node is measured on the clock of the kernel, from the end of the previous node.
    private val mark  = mutable.Map.empty[String, Long]
    private val items = mutable.Map.empty[String, Int]

    private def say(eid: Flow.Id.Execution, json: String): Unit =
        scala.util.Try(ujson.read(json).obj.head).toOption.foreach { (kind, body) =>
            val flow = body.obj.get("flowId").map(_.str).getOrElse("")
            val step = body.obj.get("stepName").map(_.str).getOrElse("")
            val now  = java.lang.System.currentTimeMillis
            def out(s: String) = java.lang.System.err.println(s"  $flow ${eid.value.take(8)} | $s")
            def since = { val t = now - mark.getOrElse(eid.value, now); mark(eid.value) = now; t }
            kind match
                case "Created"   => mark(eid.value) = now; out("created")
                case "Completed" => out("completed")
                case "Failed"    => out(s"FAILED: ${body.obj.get("error").map(_.str).getOrElse("")}")
                case "StepCompleted" if step.contains('~') =>
                    val node = step.takeWhile(_ != '~')
                    val n    = items.getOrElse(s"${eid.value}/$node", 0) + 1
                    items(s"${eid.value}/$node") = n
                    if n % 100 == 0 then out(s"  $node: $n items")
                case "StepCompleted" => out(f"$step%-12s ${since}%6d ms")
                case _ => ()
        }

    // --- FlowStore: delegate, then journal the writes ---

    def claimReady(
        served: Set[(Flow.Id.Workflow, String)],
        executorId: Flow.Id.Executor,
        lease: Duration,
        limit: Int,
        timeout: Duration
    )(using Frame): Seq[FlowStore.Claimed] < (Async & Abort[FlowStoreException]) =
        inner.claimReady(served, executorId, lease, limit, timeout).map(_.map(c => Journaled(c)))

    def createExecutionIfAbsent(
        executionId: Flow.Id.Execution,
        status: Flow.Status,
        event: Flow.Event,
        hash: String,
        fields: Dict[String, FlowStore.FieldData]
    )(using Frame): Boolean < (Async & Abort[FlowStoreException]) =
        inner.createExecutionIfAbsent(executionId, status, event, hash, fields).map { created =>
            if !created then false
            else
                append(executionId, Seq(
                    s"executions: ${key(executionId)}: flow: ${ujson.Str(event.flowId.value).render()}",
                    s"executions: ${key(executionId)}: hash: ${ujson.Str(hash).render()}"
                )).andThen(sync(executionId)).andThen(true)
        }

    def signal[V: Tag: Schema](executionId: Flow.Id.Execution, name: String, value: V, event: Flow.Event)(using
        Frame
    ): FlowStore.SignalOutcome < (Async & Abort[FlowStoreException]) =
        inner.signal(executionId, name, value, event).map(out => sync(executionId).andThen(out))

    def requestCancel(executionId: Flow.Id.Execution)(using Frame): FlowStore.CancelOutcome < (Async & Abort[FlowStoreException]) =
        inner.requestCancel(executionId).map(out => sync(executionId).andThen(out))

    def getExecution(executionId: Flow.Id.Execution)(using Frame) = inner.getExecution(executionId)

    def listExecutions(flowId: Flow.Id.Workflow, filter: Maybe[FlowStore.ExecutionFilter], limit: Maybe[Int], offset: Int)(using Frame) =
        inner.listExecutions(flowId, filter, limit, offset)

    def getField[V: Tag: Schema](executionId: Flow.Id.Execution, name: String)(using Frame) = inner.getField[V](executionId, name)

    def getAllFields(executionId: Flow.Id.Execution)(using Frame) = inner.getAllFields(executionId)

    def getHistory(executionId: Flow.Id.Execution, limit: Maybe[Int], offset: Int)(using Frame) =
        inner.getHistory(executionId, limit, offset)

    def putWorkflow(meta: FlowEngine.WorkflowInfo)(using Frame) = inner.putWorkflow(meta)

    def getWorkflow(id: Flow.Id.Workflow)(using Frame) = inner.getWorkflow(id)

    def listWorkflows(using Frame) = inner.listWorkflows

    // @what: A claim whose every write is journaled once the memory store has accepted it.
    private final class Journaled(c: FlowStore.Claimed) extends FlowStore.Claimed:
        private def eid                   = c.state.executionId
        def state: FlowStore.ExecutionState = c.state
        def satisfied: Set[String]        = c.satisfied

        def appendEvent(event: Flow.Event)(using Frame) = c.appendEvent(event).map(o => sync(eid).andThen(o))

        def recordWait(path: String, wake: Flow.Wake, event: Flow.Event)(using Frame) =
            c.recordWait(path, wake, event).map(o => sync(eid).andThen(o))

        def renewClaim(lease: Duration)(using Frame) = c.renewClaim(lease)

        def updateStatus(status: Flow.Status, event: Flow.Event)(using Frame) =
            c.updateStatus(status, event).map(o => sync(eid).andThen(o))

        def recordProgress[V](path: String, value: Maybe[V], event: Flow.Event)(using Tag[V], Schema[V], Frame) =
            c.recordProgress(path, value, event).map(o => sync(eid).andThen(o))

        def finish(outcome: FlowStore.Claimed.Outcome)(using Frame) = c.finish(outcome).map(o => sync(eid).andThen(o))
    end Journaled
end CueFlowStore

object CueFlowStore:
    // @what: A journaled store over a fresh memory store. The journal goes to dir.
    def init(dir: String)(using Frame): FlowStore < (Sync & Scope) =
        for
            inner <- FlowStore.initMemory
            mutex <- Meter.initMutex
        yield new CueFlowStore(inner, JPath.of(dir), mutex)

    // @what: The fields of a journaled execution, as the store wrote them, read back through Polaris.
    def fields(dir: String, eid: String)(using Frame): Dict[String, FlowStore.FieldData] < (Async & Abort[String]) =
        Tools.read(dir, s"executions.${ujson.Str(eid).render()}.fields").map { v =>
            v.obj.foldLeft(Dict.empty[String, FlowStore.FieldData]) { case (acc, (name, f)) =>
                val fd = ujson.Obj("value" -> ujson.Str(f("value").render()), "tag" -> f("tag")).render()
                Json.decode[FlowStore.FieldData](fd) match
                    case Result.Success(d) => acc.update(name, d)
                    case _                 => acc
            }
        }
end CueFlowStore
