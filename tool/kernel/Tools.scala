// @what: the calls to the CUE toolchain. Polaris (cue-extended) reads and writes values, `cue vet` decides.
// @invariant: the kernel holds no CUE logic of its own.

package kernel

import kyo.*

import java.nio.file.{Files, Path as JPath}
import scala.jdk.CollectionConverters.*

object Tools:

    // @what: the CUE toolchain, found on the PATH. A project pins both in its mise.toml.
    // @ref: @/mise.toml
    val CueExtended = "cue-extended"
    val Cue         = "cue"

    // @what: The root of the CUE module that holds dir (the nearest cue.mod above it), and dir relative to it.
    def module(dir: String): (JPath, String) =
        val abs  = JPath.of(dir).toAbsolutePath.normalize
        val root = Iterator.iterate(abs)(_.getParent).takeWhile(_ != null).find(d => Files.isDirectory(d.resolve("cue.mod")))
            .getOrElse(JPath.of("").toAbsolutePath)
        (root, "./" + root.relativize(abs).toString)

    private def call(cwd: JPath, args: String*)(using Frame): Answer < (Async & Abort[String]) =
        Run.run(Cmd(args, 120000), "", cwd = Present(cwd), env = Project.cueEnv).map { a =>
            if a.exit == 0 then a
            else Abort.fail(s"${args.mkString(" ")}: exit ${a.exit}\n${a.err}${a.out}")
        }

    // @what: The value at path in the package of dir.
    def read(dir: String, path: String)(using Frame): ujson.Value < (Async & Abort[String]) =
        val (root, pkg) = module(dir)
        call(root, CueExtended, "render", pkg, "--path", path, "--mode", "yaml", "--json").map { a =>
            fromYaml(org.yaml.snakeyaml.Yaml().load[Any](ujson.read(a.out)("yaml").str))
        }

    // @what: Replaces the value at path, a field of file in the package of dir. Creates the file first if needed.
    def set(dir: String, file: String, pkg: String, path: String, v: ujson.Value)(using Frame): Unit < (Async & Abort[String]) =
        Sync.defer {
            val target = JPath.of(dir, file)
            if !Files.exists(target) then
                Files.writeString(target, s"// Generated by the kernel. Do not edit.\npackage $pkg\n\n$path: {}\n"): Unit
            val tmp = Files.createTempFile("kernel-", ".cue")
            // @what: JSON is valid CUE. Indented, patch keeps one entry per line.
            Files.writeString(tmp, ujson.write(v, indent = 1)): Unit
            tmp
        }.map { tmp =>
            call(JPath.of("").toAbsolutePath, CueExtended, "patch", "set", path, "--value-file", tmp.toString, "-f", file,
                "--dir", JPath.of(dir).toAbsolutePath.toString)
                .map(_ => Sync.defer(Files.delete(tmp)))
        }

    // @what: cue fmt on files, as the cue fmt hook of a project formats them. Never for a capture under gen.
    def cueFmt(files: Seq[String])(using Frame): Unit < (Async & Abort[String]) =
        if files.isEmpty then Kyo.unit
        else call(JPath.of("").toAbsolutePath, (Seq(Cue, "fmt") ++ files.map(f => JPath.of(f).toAbsolutePath.toString))*).map(_ => ())

    // @what: cue-extended fmt on files.
    def fmt(files: Seq[String])(using Frame): Unit < (Async & Abort[String]) =
        if files.isEmpty then Kyo.unit
        else call(JPath.of("").toAbsolutePath, (Seq(CueExtended, "fmt", "--files") ++ files.map(f => JPath.of(f).toAbsolutePath.toString))*).map(_ => ())

    // @what: Decides. The package must not be ⊥. Right(()) or Left(what CUE said).
    def vet(pkgDir: String, tags: Seq[String] = Nil)(using Frame): Either[String, Unit] < Async =
        val (root, pkg) = module(pkgDir)
        Run.run(Cmd(Seq(Cue, "vet", "-c") ++ tags.flatMap(t => Seq("-t", t)) :+ pkg, 120000), "", cwd = Present(root), env = Project.cueEnv).map { a =>
            if a.exit == 0 then Right(()) else Left(a.err + a.out)
        }

    // @what: decides on every package of the module at root, as a person runs it.
    def vetAll(root: JPath)(using Frame): Either[String, Unit] < Async =
        Run.run(Cmd(Seq(Cue, "vet", "-c", "./..."), 300000), "", cwd = Present(root), env = Project.cueEnv).map { a =>
            if a.exit == 0 then Right(()) else Left(a.err + a.out)
        }

    // @what: the value at expr of an imported package, from the module at root. It reads the tool module at the version the project pins.
    def exportedImport(root: JPath, pkg: String, expr: String)(using Frame): ujson.Value < (Async & Abort[String]) =
        call(root, Cue, "export", pkg, "-e", expr, "--out", "json").map(a => ujson.read(a.out))

    // @what: the value at expr in the package of dir, as JSON, with build tags. For files that cue vet skips by default.
    def exported(dir: String, expr: String, tags: Seq[String])(using Frame): ujson.Value < (Async & Abort[String]) =
        val (root, pkg) = module(dir)
        call(root, (Seq(Cue, "export") ++ tags.flatMap(t => Seq("-t", t)) ++ Seq(pkg, "-e", expr, "--out", "json"))*).map(a => ujson.read(a.out))

    private def fromYaml(x: Any): ujson.Value = x match
        case r: AnyRef if r eq null   => ujson.Null
        case m: java.util.Map[?, ?]   => ujson.Obj.from(m.asScala.toSeq.map((k, v) => String.valueOf(k) -> fromYaml(v)))
        case l: java.util.List[?]     => ujson.Arr.from(l.asScala.map(fromYaml))
        case s: String                => ujson.Str(s)
        case b: java.lang.Boolean     => ujson.Bool(b)
        case n: java.lang.Number      => ujson.Num(n.doubleValue)
        case other                    => ujson.Str(String.valueOf(other))
end Tools
