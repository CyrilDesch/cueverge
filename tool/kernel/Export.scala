// @what: the versioned projection of the raw journal. One export file per execution and per Claude session.
// @invariant: the journal package vets after every write. An export that its raw journal does not give is refused.
// @ref: @/tool/cue/rules/export.rules.cue

package kernel

import kyo.*

import java.nio.file.{Files, Path as JPath}

object Export:

    private def write(file: JPath, path: String, key: String, v: ujson.Value): Unit =
        val body = s"// Generated by the kernel from the raw journal (kernel/rules/export.rules.cue). Do not edit.\n" +
            s"package journal\n\nexports: $path: ${ujson.Str(key).render()}: ${ujson.write(v, indent = 1)}\n"
        Files.writeString(file, body): Unit

    // @what: Writes the missing export files of the journal of o, then checks the journal package.
    def all(o: Options)(using Frame): Unit < (Async & Abort[String]) = of(Main.journalDir(o), Main.journalRulesDir(o))

    // @what: the exports of the journal in dir, as the export rule wired in rules computes them.
    def of(dir: String, rules: String)(using Frame): Unit < (Async & Abort[String]) =
        Tools.exported(rules, "exports", Seq(Main.JournalTag)).map { ex =>
            Sync.defer {
                val executions = ex.obj.get("executions").map(_.obj.toSeq).getOrElse(Nil).map((id, v) => (JPath.of(dir, s"$id.export.cue"), "executions", id, v))
                val traces     = ex.obj.get("traces").map(_.obj.toSeq).getOrElse(Nil).map((s, v) => (JPath.of(dir, s"claude-$s.export.cue"), "traces", s, v))
                val missing    = (executions ++ traces).filterNot((f, _, _, _) => Files.exists(f))
                missing.foreach((f, path, key, v) => write(f, path, key, v))
                // @what: the raw journal of every exported execution, compressed, so that any checkout can check the export again.
                // @invariant: written once, since an exported execution is over.
                (executions ++ traces).foreach { (f, _, _, _) =>
                    val raw     = JPath.of(f.toString.stripSuffix(".export.cue") + ".gen.cue")
                    val archive = JPath.of(dir, "raw", raw.getFileName.toString + ".gz")
                    if Files.exists(raw) && !Files.exists(archive) then
                        Files.createDirectories(archive.getParent): Unit
                        val out = java.util.zip.GZIPOutputStream(Files.newOutputStream(archive))
                        try Files.copy(raw, out): Unit finally out.close()
                }
                missing.map(_._1.toString)
            }.map { written =>
                if written.isEmpty then Kyo.unit
                else
                    Tools.fmt(written).andThen(Tools.vet(rules, Seq(Main.JournalTag))).map {
                        case Right(())   => Sync.defer(java.lang.System.err.println(s"  export | ${written.size} file(s) written, journal vets"))
                        case Left(report) => Abort.fail(s"the exports do not match the journal:\n${Main.clip(report, 1500)}")
                    }
            }
        }
end Export
